if __name__ == "__main__":
    print("=" * 70)
    print("🚀 DEEPSEEKMATH GRPO LOSS & VERIFIER WALKTHROUGH (arXiv:2402.03300)")
    print("🔬 Scope Note: Numerical illustration of the loss on synthetic tensors — no 7B model is trained here.")
    print("=" * 70)
    torch.manual_seed(42)

    # Question Prompt
    prompt = "Question: Sarah has 15 apples. She gives 4 to Tom and 3 to Ben. How many apples does she have left?"
    ground_truth = "8"
    print(f"\nPrompt: {prompt}")
    print(f"Ground Truth Answer: {ground_truth}")

    # Simulate G = 4 candidate reasoning paths generated by model
    candidates = [
        "<think> 15 - 4 = 11. Then 11 - 3 = 8. </think> <answer>8</answer>",       # Correct + tags
        "<think> Sarah starts with 15. Gives away 4+3=7. 15-7=8. </think> <answer>8</answer>", # Correct + tags
        "<think> 15 - 4 = 11. 11 - 3 = 7. </think> <answer>7</answer>",            # Arithmetic error + tags
        "She has 10 apples left."                                                  # Wrong + No tags
    ]

    print("\n--- Evaluating Candidate Completions (Robust vs. Naive Verifiers) ---")
    print("💡 Educational Note on Reward Hacking:")
    print("   Under a naive un-gated verifier, Candidate 3 (wrong arithmetic) receives 0.1 purely for <think> tags,")
    print("   outscoring an honest wrong answer! A model trained on that naive verifier learns to hack tags instead of math.")
    print("   Our robust verifier gates the format bonus on correctness (+0.1 ONLY if is_correct) and requires <answer> tags.\n")

    rewards_list = []
    for i, c in enumerate(candidates):
        r_robust = verify_math_candidate(c, ground_truth, strict_format=True)
        r_naive = verify_math_candidate(c, ground_truth, strict_format=False)
        rewards_list.append(r_robust)
        print(f"Candidate {i+1} [Robust: {r_robust:.1f} | Naive: {r_naive:.1f}]: {c}")

    rewards = torch.tensor(rewards_list)
    advantages = compute_group_advantages(rewards)
    print("\n--- Group-Relative Advantages (A_i from Robust Verifier) ---")
    for i, adv in enumerate(advantages.tolist()):
        print(f"Candidate {i+1} Advantage: {adv:+.4f}")

    # Simulate token log probabilities: Group G=4, Sequence length T=10
    G, T = 4, 10
    mask = torch.ones(G, T)
    logprobs_old = torch.randn(G, T)
    logprobs_ref = logprobs_old.clone()

    # Create trainable policy parameter tensor to demonstrate gradient descent step
    policy_delta = nn.Parameter(torch.zeros(G, T))
    optimizer = torch.optim.AdamW([policy_delta], lr=0.05)

    print("\n--- Training Step: Shifting Policy towards High-Advantage Trajectories ---")
    for step in range(1, 6):
        optimizer.zero_grad()
        logprobs_policy = logprobs_old + policy_delta
        loss = grpo_loss(
            logprobs_policy=logprobs_policy,
            logprobs_old=logprobs_old,
            logprobs_ref=logprobs_ref,
            advantages=advantages,
            mask=mask,
            clip_eps=0.2,
            beta=0.04
        )
        loss.backward()
        optimizer.step()
        print(f"GRPO Step {step} | Loss: {loss.item():.5f}")

    print("\n" + "=" * 70)
    print("✅ GRPO LOSS WALKTHROUGH COMPLETED SUCCESSFULLY!")
    print("You have verified group normalization, clipped surrogate loss, and analytical KL divergence.")
