import re
import torch
import torch.nn as nn
import torch.nn.functional as F

# -------------------------------------------------------------
# 1. Rule-Based Mathematical Verifier (GSM8K Style)
# -------------------------------------------------------------
def extract_answer(text: str) -> str:
    """Extracts final mathematical answer from reasoning text."""
    match = re.search(r"<answer>(.*?)</answer>", text)
    if match:
        return match.group(1).strip()
    numbers = re.findall(r"-?\d+", text)
    return numbers[-1] if numbers else ""

def verify_math_candidate(candidate_text: str, ground_truth: str) -> float:
    """Awards 1.0 for exact answer match, +0.1 format bonus for <think> tags."""
    extracted = extract_answer(candidate_text)
    is_correct = (extracted == ground_truth.strip())
    reward = 1.0 if is_correct else 0.0
    if "<think>" in candidate_text and "</think>" in candidate_text:
        reward += 0.1
    return reward

# -------------------------------------------------------------
# 2. Group Advantage Normalizer
# -------------------------------------------------------------
def compute_group_advantages(rewards: torch.Tensor, eps: float = 1e-8) -> torch.Tensor:
    """
    Standardizes rewards within each candidate group G.
    A_i = (r_i - mean(rewards)) / (std(rewards) + eps)
    """
    mean = rewards.mean()
    std = rewards.std(unbiased=False)
    if std < eps:
        return torch.zeros_like(rewards)
    return (rewards - mean) / (std + eps)

# -------------------------------------------------------------
# 3. GRPO Loss Engine
# -------------------------------------------------------------
def grpo_loss(
    logprobs_policy: torch.Tensor,
    logprobs_old: torch.Tensor,
    logprobs_ref: torch.Tensor,
    advantages: torch.Tensor,
    mask: torch.Tensor,
    clip_eps: float = 0.2,
    beta: float = 0.04
) -> torch.Tensor:
    """
    Computes GRPO loss with PPO clipped ratio and analytical KL penalty.
    Shapes:
      logprobs: (G, T)
      advantages: (G,)
      mask: (G, T)
    """
    # Probability ratios r_t = exp(log_pi - log_pi_old)
    ratios = torch.exp(logprobs_policy - logprobs_old)

    # Clipped surrogate objective
    adv = advantages.unsqueeze(-1)  # (G, 1)
    surr1 = ratios * adv
    surr2 = torch.clamp(ratios, 1.0 - clip_eps, 1.0 + clip_eps) * adv
    ppo_obj = torch.min(surr1, surr2)

    # Analytical KL penalty: exp(ref - pol) - (ref - pol) - 1
    kl = torch.exp(logprobs_ref - logprobs_policy) - (logprobs_ref - logprobs_policy) - 1.0

    # Token-level objective
    token_obj = (ppo_obj - beta * kl) * mask
    candidate_obj = token_obj.sum(dim=-1) / mask.sum(dim=-1).clamp(min=1.0)
    return -candidate_obj.mean()

